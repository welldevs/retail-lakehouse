"""On-demand DAG: synthetic orders as an EVENT LOG (RAW + Silver).

Fifth source, and the SECOND DERIVED one: it consumes the Silver the others produced and
returns a new RAW. Phase 1's golden rule still holds, shifted one level — the ORDER is
invented; who buys, what is bought, how much it costs and where they live are not.

THREE DIFFERENCES IN SHAPE FROM THE OTHER FOUR
----------------------------------------------
1. `export_reference` runs ONCE and feeds all four warehouses AND the whole window. The
   Source is FROZEN (dependencies = []) and cannot open a connection to the Lakehouse, so
   the platform first materializes customers, catalog, price calendar and premises into
   four flat JSON files. Putting it inside each warehouse's branch would repeat the same
   query 16 times to produce the same file.

2. EACH BRANCH WALKS THE WINDOW OF DAYS INTERNALLY, instead of there being 4 x N tasks. The
   graph stays stable as the window grows, and the granularity that is lost costs nothing
   in retries: `extract` skips a partition with `_SUCCESS` (not a failure), `land` skips an
   object with the expected checksum, and `validate`/`verify-landing` are pure. Re-running
   the whole branch after a failure on the third day redoes only what was missing.

3. THE WINDOW IS A PARAMETER, not "today". In the other four the partition is the snapshot
   of the run day; here `ingestion_date` is the ORDER DATE, and it is bounded by the
   catalog that exists. `export-orders-reference` REFUSES a window in which some
   (warehouse, day) has no catalog snapshot on or before it — an order on that day would
   have to invent a price. Measured on 2026-08-28: the 4 warehouses have catalog from
   08-24 to 08-27.

There is NO NETWORK in any generation step — no pool, no throttle, no guard_date. `extract`
reads local JSON and writes local JSON; the only external I/O is `land`.

schedule=None for the same structural reason as the Callejero and the customer base: there
is no "new data" to fetch. The order window changes when SOMEONE decides to change it.

REGENERATING SWAPS THE ORDERS, and that differs from the customer base. There, raising
`count` with the same seed is additive. Here what is additive is the TIME AXIS: each
(warehouse, day) derives its own sub-seed from sha256(seed|wh|day), so adding a day to the
window leaves the days already generated byte-for-byte identical. What is NOT additive:
another seed, another reference, or another premises table — all three swap the orders
behind the same order_id, and the manifest records all three in `history`.
"""

from __future__ import annotations

import logging
import os
import subprocess
from datetime import date, datetime, timedelta

from airflow import DAG

from airflow.utils.trigger_rule import TriggerRule

try:  # Airflow 3.x
    from airflow.providers.standard.operators.python import (
        PythonOperator,
        ShortCircuitOperator,
    )
except ImportError:  # Airflow 2.x
    from airflow.operators.python import PythonOperator, ShortCircuitOperator

REPO = os.environ.get("RETAIL_REPO_ROOT", "/opt/retail-lakehouse")
DATA_ROOT = f"{REPO}/data/orders"
REFERENCE_ROOT = f"{REPO}/data/orders-reference"

ORDERS_SOURCE_SRC = f"{REPO}/sources/simulated-orders-source/src"
PLATFORM_SRC = f"{REPO}/platform/src"

SOURCE_PYTHON = os.environ.get("RETAIL_SOURCE_PYTHON", "python3")
PLATFORM_PY = os.environ.get("RETAIL_PLATFORM_PYTHON", f"{REPO}/platform/.venv/bin/python")

# The same four warehouses as the other sources: each one's service area comes from
# warehouse_service_area, and a customer of W only orders from W.
WAREHOUSES = os.environ.get("RETAIL_ORDERS_WAREHOUSES", "mad1,bcn1,svq1,vlc1").split(",")

# Exit codes from the source's CONTRACT.md section 7.
EXIT_OK = 0
EXIT_PARTIAL = 1
EXIT_FATAL = 2


def _run(argv: list[str], env_extra: dict | None = None) -> int:
    """Run and FORWARD the output, line by line, to the task log."""
    env = dict(os.environ)
    if env_extra:
        env.update(env_extra)
    print("$", " ".join(argv))
    process = subprocess.Popen(
        argv, cwd=REPO, env=env, text=True,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, bufsize=1,
    )
    with process.stdout:
        for line in process.stdout:
            print(line, end="")
    return process.wait()


def _run_source(argv: list[str]) -> int:
    """Invoke the Source on Airflow's interpreter. Safe because dependencies = []."""
    return _run([SOURCE_PYTHON, "-m", "simulated_orders_source", *argv],
                {"PYTHONPATH": ORDERS_SOURCE_SRC})


def _run_platform(argv: list[str]) -> int:
    """Invoke the platform in its separate venv, with code from the mounted repo."""
    return _run([PLATFORM_PY, "-m", "retail_platform", *argv],
                {"PYTHONPATH": PLATFORM_SRC})


def _log_task_failure(context: dict) -> None:
    """CR-005: the only structured record a task failure leaves, besides the scheduler's
    internal state. Uses the logger the task already writes to
    (`logging.getLogger("airflow.task")`) — no new file, no new service.
    """
    ti = context.get("task_instance")
    exc = context.get("exception")
    logging.getLogger("airflow.task").error(
        "task failed dag_id=%s task_id=%s run_id=%s try_number=%s exception_type=%s "
        "exception=%s",
        context.get("dag").dag_id if context.get("dag") else "?",
        ti.task_id if ti else "?",
        context.get("run_id"),
        ti.try_number if ti else "?",
        type(exc).__name__ if exc is not None else "?",
        exc,
    )


def partition_path(order_date: str, warehouse: str) -> str:
    return f"{DATA_ROOT}/ingestion_date={order_date}/wh={warehouse}"


def reference_path(window_to: str) -> str:
    return f"{REFERENCE_ROOT}/ingestion_date={window_to}"


def _window(params: dict) -> list[str]:
    """Days of the window, inclusive at both ends. Refuses an inverted window.

    The window is explicit and not derived from `ds`: `ingestion_date` here is the ORDER
    date, and falling back to the run day would generate orders on a day that may not even
    have a catalog.
    """
    start = date.fromisoformat(params["window_from"])
    end = date.fromisoformat(params["window_to"])
    if end < start:
        raise RuntimeError(
            f"inverted window: window_from={start} > window_to={end}"
        )
    return [(start + timedelta(days=n)).isoformat() for n in range((end - start).days + 1)]


def export_reference(params: dict, **_) -> None:
    """The bridge between the Lakehouse and the FROZEN Source. Runs once, covers the 4 wh and the window.

    `export-orders-reference` already refuses with an actionable message when catalog or
    customers are missing, and when some (warehouse, day) in the window has no price base —
    there is no gate to duplicate here.
    """
    days = _window(params)
    code = _run_platform([
        "export-orders-reference",
        "--out", REFERENCE_ROOT,
        "--date", params["window_to"],
        "--from", params["window_from"],
        "--to", params["window_to"],
    ])
    if code != EXIT_OK:
        raise RuntimeError(f"export-orders-reference failed (exit {code})")
    print(f"reference covers {len(days)} day(s): {days[0]} to {days[-1]}")


def already_landed(warehouse: str, params: dict, **_) -> bool:
    """Short-circuit that looks at the DESTINATION, same reasoning as the other four sources.

    Here the gate asks about the WHOLE WINDOW: it carries on if ANY day is not yet landed
    and verified. There is no per-day gate because the branch is per warehouse; a gate that
    required all four days complete in order to skip would be the same thing.

    With `overwrite`, the gate switches OFF. Without this the parameter would be inert:
    whoever triggers a regeneration asks for exactly the case the gate considers "nothing
    to do".
    """
    if params.get("overwrite"):
        print("overwrite requested: gate off, the branch runs even though already landed.")
        return True

    pending = []
    for day in _window(params):
        code = _run_platform(["verify-landing", partition_path(day, warehouse)])
        if code != EXIT_OK:
            pending.append(day)
    if not pending:
        print("whole window already landed and verified at the destination: nothing to do.")
        return False
    print(f"{len(pending)} day(s) pending: {pending}. Continuing the pipeline.")
    return True


def extract(warehouse: str, params: dict, **_) -> None:
    overwrite = bool(params.get("overwrite"))
    reference = reference_path(params["window_to"])
    if not os.path.isdir(reference):
        raise RuntimeError(
            f"missing reference: {reference}. The export_reference task should have "
            f"produced it — check its log."
        )

    for day in _window(params):
        partition = partition_path(day, warehouse)
        if os.path.exists(os.path.join(partition, "_SUCCESS")) and not overwrite:
            print(f"{day}: partition already complete and immutable: extract skipped (not a failure).")
            continue

        argv = [
            "extract",
            "--reference", reference,
            "--out", DATA_ROOT,
            "--wh", warehouse,
            "--date", day,
            "--seed", str(params["seed"]),
        ]
        if overwrite:
            argv.append("--overwrite")

        code = _run_source(argv)
        if code == EXIT_FATAL:
            raise RuntimeError(
                f"{day}: extract failed fatally (exit {code}); retrying will not fix it"
            )
        if code == EXIT_PARTIAL:
            raise RuntimeError(f"{day}: partial extract (exit {code}): there are entries in failures[]")
        if code != EXIT_OK:
            raise RuntimeError(f"{day}: extract returned exit {code}")


def validate(warehouse: str, params: dict, **_) -> None:
    """--reference is NOT optional here, as in the customers source and for the same reason.

    The central guarantees — the product exists in that warehouse's catalog on that date,
    the price paid is the observed price, the customer belongs to that warehouse — can only
    be re-checked by rereading the same reference that generated the partition. A validator
    that only checks checksums would prove integrity, not coherence.
    """
    reference = reference_path(params["window_to"])
    for day in _window(params):
        code = _run_source([
            "validate", partition_path(day, warehouse),
            "--reference", reference, "--strict",
        ])
        if code != EXIT_OK:
            raise RuntimeError(f"{day}: validate rejected the partition (exit {code})")


def land(warehouse: str, params: dict, **_) -> None:
    for day in _window(params):
        code = _run_platform(["land", partition_path(day, warehouse)])
        if code != EXIT_OK:
            raise RuntimeError(f"{day}: land failed (exit {code})")


def verify_landing(warehouse: str, params: dict, **_) -> None:
    for day in _window(params):
        code = _run_platform(["verify-landing", partition_path(day, warehouse)])
        if code != EXIT_OK:
            raise RuntimeError(f"{day}: verify-landing rejected the destination (exit {code})")


def silver(**_) -> None:
    """Silver `dbt build`, with the gate applied by the platform.

    THE GATE DOES NOT LIVE HERE, and it used to — that was the defect. Each DAG carried its
    own partial copy of the decision (excluding its OWN source, and nothing else), the
    Makefile carried the full version, and all six diverged. This DAG had no gate at all and
    failed every day from the moment `silver_live_order_state` was born, because the Iceberg
    projection can only be read when the catalog responds — and the catalog has nothing to
    do with this DAG's source.

    Now there is one verb: `retail_platform silver-build` observes what has landed and
    whether the catalog responds, and builds `--exclude`/`--vars` itself. See silver_gate.py.
    """
    code = _run_platform([
        "silver-build",
        "--project-dir", f"{REPO}/platform/dbt",
        "--profiles-dir", f"{REPO}/platform/dbt",
    ])
    if code != EXIT_OK:
        raise RuntimeError(f"dbt build failed (exit {code})")


with DAG(
    dag_id="simulated_orders_events",
    description="Synthetic orders as an event log, with real customers and prices (RAW + Silver)",
    schedule=None,
    start_date=datetime(2026, 8, 28),
    catchup=False,
    max_active_runs=1,
    params={
        # The window that is landed and sealed (Phase 7: 2026-08-24..09-01). Triggering with
        # these defaults re-verifies it without generating anything new. Widening it is a
        # regeneration (CR-010), and outside the catalog coverage the export REFUSES
        # instead of inventing a price.
        "window_from": "2026-08-24",
        "window_to": "2026-09-01",
        "seed": 20260828,
        # Deliberate regeneration. Adding a DAY does not need this — each day derives its
        # own sub-seed and the earlier ones stay identical. `overwrite` is for changing the
        # seed or the premises table, which swap the orders behind the same order_id.
        "overwrite": False,
    },
    default_args={
        "owner": "data-platform",
        "retries": 0,
        "retry_delay": timedelta(minutes=5),
        "on_failure_callback": _log_task_failure,
    },
    tags=["source:simulated", "layer:raw", "layer:silver", "model:events"],
    doc_md=__doc__,
) as dag:

    build_reference = PythonOperator(
        task_id="export_reference",
        python_callable=export_reference,
        retries=1,
    )

    build_silver = PythonOperator(
        task_id="silver",
        python_callable=silver,
        retries=1,
        # Same rule as the other DAGs, and for the same measured defect: with all_success,
        # a single short-circuited warehouse would drag silver into `skipped` and the
        # freshly landed data of the other three would never be transformed.
        trigger_rule=TriggerRule.NONE_FAILED_MIN_ONE_SUCCESS,
    )

    for warehouse in WAREHOUSES:
        gate = ShortCircuitOperator(
            task_id=f"skip_if_landed_{warehouse}",
            python_callable=already_landed,
            op_kwargs={"warehouse": warehouse},
            # With more than one warehouse the default True is WRONG: the short-circuit
            # would skip ALL of the downstream, ignoring each task's trigger_rule, including
            # that of `silver`, which is shared. See mercadona_catalog_daily.
            ignore_downstream_trigger_rules=False,
        )

        do_extract = PythonOperator(
            task_id=f"extract_{warehouse}",
            python_callable=extract,
            op_kwargs={"warehouse": warehouse},
            # Data failure. Retrying does not fix an incoherent reference or an invalid window.
            retries=0,
        )

        do_validate = PythonOperator(
            task_id=f"validate_{warehouse}",
            python_callable=validate,
            op_kwargs={"warehouse": warehouse},
            retries=0,
        )

        do_land = PythonOperator(
            task_id=f"land_{warehouse}",
            python_callable=land,
            op_kwargs={"warehouse": warehouse},
            # The network IS retryable, and `land` is idempotent: an object with the
            # expected checksum is skipped, not re-uploaded.
            retries=2,
        )

        do_verify = PythonOperator(
            task_id=f"verify_landing_{warehouse}",
            python_callable=verify_landing,
            op_kwargs={"warehouse": warehouse},
            retries=1,
        )

        build_reference >> gate >> do_extract >> do_validate >> do_land >> do_verify
        do_verify >> build_silver
