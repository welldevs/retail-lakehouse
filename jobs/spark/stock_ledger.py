#!/usr/bin/env python3
"""THE STOCK BALANCE WITH REPLENISHMENT — the job whose SHAPE SQL does not express.

    make stock-ledger

WHY THIS JOB EXISTS IN SPARK, AND WHY IT IS NOT ABOUT VOLUME.

The volume trigger did NOT fire in this project, and that is measured: the natural
candidate — the basket self-join, 37.9 million pairs — runs in ~1.5 s and ~2.4 GB on a
single DuckDB node. Inflating data to justify an engine would be the defect this repository
spent six phases hunting down. So Spark comes in through another door, and it was already
open.

TWO REASONS, AND PERFORMANCE IS NEITHER OF THEM.

FIRST, interop. ARCHITECTURE justified Iceberg by "interop between engines", and both
writers were Python using the same library — a property CLAIMED and never demonstrated.
This job is the catalog's third writer and the first one outside Python.

SECOND, shape. A running sum is trivial SQL:

    sum(consumption) over (partition by series order by day)

This is not a running sum. It is a running sum whose INPUTS ARE GENERATED BY DECISIONS
TAKEN FROM THE STATE ITSELF:

    balance drops below the point  ->  issues a purchase order
                                   ->  the order arrives in `supplier_lead_days` days
                                   ->  the arrival CHANGES the balance of the following days
                                   ->  which decides whether there is a new order

A window function cannot express feedback: it reads the whole partition but cannot write
back into it. That was MEASURED, not claimed — `make check-spark-iceberg`, question S7b,
runs the same input through both shapes: the SQL running sum diverges on 14 of the 30 days
of the test case and reaches a balance of -70, because there is no way to inject the arrival
that its own decision generated.

`applyInPandas` expresses it, and parallelizes by series: each (warehouse, product) is an
independent loop, and there are ~17 thousand of them.

WHAT THIS JOB IS NOT. It is not the project's default path. `make silver`, `make warehouse`,
the dashboard and the five DAGs run without it — the gate in `silver_gate.py` drops from the
build whatever depends on a table that does not exist. Running without Spark is a tested
case, not an accident.

INPUT     operations.stock_consumption   written by the platform (pyiceberg) from the
                                         consumption OBSERVED in silver_order_line
          stock_premises_seed.csv        the declared policy: how many days to cover
OUTPUT    operations.stock_ledger        grain (warehouse, product, day)

`construir_ledger` and `ler_premissas` keep their historical names because
platform/src/retail_platform/spark_evidence.py imports them. The summary keys printed at
the end (`linhas`, `series`, `demanda`, ..., `segundos`) are parsed by spark_evidence.py, so
they stay as they are too.
"""

from __future__ import annotations

import csv
import hashlib
import math
import os
import sys
import time

sys.path.insert(0, "/repo")

from jobs.spark.session import CATALOGO, sessao  # noqa: E402

NAMESPACE = os.environ.get("STOCK_NAMESPACE", "operations")
CONSUMPTION = f"{CATALOGO}.{NAMESPACE}.stock_consumption"
LEDGER = f"{CATALOGO}.{NAMESPACE}.stock_ledger"
PREMISES_CSV = os.environ.get("STOCK_PREMISES_CSV",
                              "/repo/platform/dbt/seeds/stock_premises_seed.csv")

SCHEMA = """
    wh string, source_product_id string, stock_date date,
    opening_balance bigint, units_received bigint, units_demanded bigint,
    units_fulfilled bigint, units_short bigint, closing_balance bigint,
    reorder_units bigint, reorder_eta date,
    mean_daily_demand double, days_of_cover double,
    written_by string
"""


def ler_premissas(path: str) -> dict:
    """Read the stock premises. They come from the SAME seed dbt loads, read as a file.

    There is no copy: the container mounts the repository at `/repo` and reads the CSV that
    `stock_premises` projects into Silver. Passing them via --conf would create a second
    place where the policy lives, and it would diverge at the first edit of the seed.
    """
    with open(path, encoding="utf-8") as handle:
        rows = {row["premise_key"]: float(row["value"])
                for row in csv.DictReader(handle)}
    missing = {"opening_days_min", "opening_days_max", "reorder_point_days",
               "reorder_target_days", "supplier_lead_days"} - set(rows)
    if missing:
        raise SystemExit(f"{path} does not declare: {sorted(missing)}")
    return rows


def opening_days(wh: str, product: str, low: float, high: float) -> float:
    """This series' opening cover, between low and high, from a hash of the series alone.

    sha256 and not `hash()`: CPython randomizes the str hash per process, and Spark runs the
    function in separate Python workers — the same series would get a different cover on each.
    Staggered on purpose (CR-017): one cover for every series made two thirds of them reorder
    on the same day, a wave no real operation has.
    """
    digest = hashlib.sha256(f"{wh}|{product}".encode("utf-8")).digest()
    fraction = int.from_bytes(digest[:8], "big") / 2 ** 64
    return low + (high - low) * fraction


def units(days: float, mean_demand: float) -> int:
    """Days of cover -> units. `floor(x + 0.5)`, not `round`.

    Python's `round` rounds 0.5 to the nearest EVEN number — 0.5 becomes 0 and 1.5 becomes
    2. For a slow-moving product, where mean demand is a fraction, that makes two series
    with the same policy receive different stock because of an IEEE 754 detail. The ledger
    would be correct and inexplicable.
    """
    return int(math.floor(days * mean_demand + 0.5))


def construir_ledger(premises: dict):
    """Build the ledger: return the function `applyInPandas` applies to each series.

    Closed over the premises on purpose: they travel to the executor as part of the
    function, not as a broadcast to be managed.
    """
    import datetime as dt

    import pandas as pd

    cover_low = premises["opening_days_min"]
    cover_high = premises["opening_days_max"]
    point_days = premises["reorder_point_days"]
    target_days = premises["reorder_target_days"]
    lead_time = int(premises["supplier_lead_days"])

    def ledger(key, pdf: "pd.DataFrame") -> "pd.DataFrame":
        wh, product = key
        pdf = pdf.sort_values("stock_date")
        mean_demand = float(pdf["mean_daily_demand"].iloc[0])

        balance = units(opening_days(wh, product, cover_low, cover_high), mean_demand)
        point = units(point_days, mean_demand)
        target = units(target_days, mean_demand)

        arrivals: dict[dt.date, int] = {}
        order_open = False
        rows = []

        for _, row in pdf.iterrows():
            day = row["stock_date"]
            if hasattr(day, "date"):
                day = day.date()

            opening = balance

            # 1. WHAT WAS ORDERED EARLIER ARRIVES. Today's order was decided `lead_time`
            #    days ago, from that day's balance — and this is what a window function
            #    cannot do.
            received = arrivals.pop(day, 0)
            if received:
                order_open = False
            balance += received

            # 2. FULFILL WHAT IS POSSIBLE. You cannot sell what is not there: the shortfall
            #    is a STOCKOUT, and it is recorded instead of becoming a negative balance.
            #    A negative balance would close the sum and lie about the shelf.
            demand = int(row["units_demanded"] or 0)
            fulfilled = min(demand, balance)
            short = demand - fulfilled
            balance -= fulfilled

            # 3. DECIDE TO REPLENISH. One open order at a time — classic min-max policy.
            #    Without this lock, a product in stockout would issue one order per day
            #    while the first was still on its way, and the cascading arrivals would
            #    produce a stock peak no real operation would have.
            ordered, arrival = 0, None
            if balance < point and not order_open:
                ordered = max(target - balance, 0)
                if ordered:
                    arrival = day + dt.timedelta(days=lead_time)
                    arrivals[arrival] = arrivals.get(arrival, 0) + ordered
                    order_open = True

            rows.append((
                wh, product, day,
                opening, received, demand, fulfilled, short, balance,
                ordered, arrival,
                mean_demand,
                (balance / mean_demand) if mean_demand > 0 else None,
                "spark",
            ))

        return pd.DataFrame(rows, columns=[
            "wh", "source_product_id", "stock_date",
            "opening_balance", "units_received", "units_demanded",
            "units_fulfilled", "units_short", "closing_balance",
            "reorder_units", "reorder_eta",
            "mean_daily_demand", "days_of_cover", "written_by",
        ])

    return ledger


def main() -> int:
    from pyspark.sql import functions as F

    premises = ler_premissas(PREMISES_CSV)
    print("premises (days) ...", {k: v for k, v in sorted(premises.items())})

    spark = sessao("stock-ledger")
    spark.sparkContext.setLogLevel("ERROR")
    start = time.time()

    consumption = spark.table(CONSUMPTION)
    window = consumption.agg(F.min("stock_date").alias("de"),
                             F.max("stock_date").alias("ate")).collect()[0]
    if window["de"] is None:
        raise SystemExit(
            f"{CONSUMPTION} is empty. Run `make stock-consumption` after `make silver`.")
    print(f"window ............ {window['de']} .. {window['ate']}")

    # ---- DENSIFY: one row per series PER DAY, even without consumption -------------
    #
    # Without this the ledger would only have rows on days with sales, and the balance
    # would "skip" the idle days — which are exactly the days a replenishment arrives. A
    # product that has not sold for three days has a balance on those three days, and days
    # of cover only mean something if the series is continuous.
    days = spark.sql(
        f"select explode(sequence(date '{window['de']}', date '{window['ate']}',"
        f" interval 1 day)) as stock_date"
    )
    series = consumption.groupBy("wh", "source_product_id").agg(
        F.sum("units_consumed").alias("total"),
        F.countDistinct("stock_date").alias("dias_com_venda"),
    )
    n_days = spark.sql(
        f"select datediff(date '{window['ate']}', date '{window['de']}') + 1 as n"
    ).collect()[0]["n"]

    # MEAN DEMAND IS OBSERVED, and divides by the days of the WINDOW — not by the days with
    # sales. Dividing by days with sales would measure "how much goes out when it goes out",
    # which is another question: a product sold once in nine days would have the same daily
    # mean as one sold every day, and would receive the same stock.
    series = series.withColumn("mean_daily_demand", F.col("total") / F.lit(float(n_days)))

    grid = series.crossJoin(days)
    ledger_input = (
        grid.join(consumption, ["wh", "source_product_id", "stock_date"], "left")
            .select("wh", "source_product_id", "stock_date", "mean_daily_demand",
                    F.coalesce(F.col("units_consumed"), F.lit(0))
                     .cast("bigint").alias("units_demanded"))
    )

    ledger = (
        ledger_input.groupBy("wh", "source_product_id")
                    .applyInPandas(construir_ledger(premises), schema=SCHEMA)
    )

    (ledger.writeTo(LEDGER)
           .tableProperty("write.format.default", "parquet")
           .createOrReplace())

    elapsed = time.time() - start
    # The aliases below are the printed keys spark_evidence.py parses: do not rename them.
    summary = spark.sql(f"""
        select count(*)                                      as linhas,
               count(distinct wh || '|' || source_product_id) as series,
               sum(units_demanded)                            as demanda,
               sum(units_fulfilled)                           as atendido,
               sum(units_short)                               as ruptura,
               count_if(units_short > 0)                      as dias_com_ruptura,
               count_if(reorder_units > 0)                    as ordens,
               sum(reorder_units)                             as unidades_pedidas,
               count_if(units_received > 0)                   as chegadas,
               round(avg(days_of_cover), 2)                   as cobertura_media
        from {LEDGER}
    """).collect()[0]

    print()
    for key in summary.asDict():
        print(f"{key:.<20} {summary[key]}")
    print(f"{'segundos':.<20} {elapsed:.1f}")
    spark.stop()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
