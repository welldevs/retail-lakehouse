"""Generates docs/indicators/{operations,prices}.md from the catalog.

    make indicators-contract

WHY GENERATED AND NOT HAND-WRITTEN. The page exists for REVIEW: someone reads the query
alongside the explanation and decides whether the indicator is right before rebuilding it
elsewhere. If the two lived in different files they would diverge at the first SQL tweak,
and the review would keep "passing", because nobody reads a query and a text side by side
looking for disagreement. Same mechanism as `docs/warehouse-evidence/` and the STAGE DDL.

The header carries the sha256 of the catalog module, NOT a date: regenerating an up-to-date
page changes no byte, so `git diff --exit-code docs/indicators/` after
`make indicators-contract` is the check that page and catalog never diverged.

It connects to nothing: the pages are reviewable without credentials or network.
"""

from __future__ import annotations

import hashlib
import os
import sys

from . import operations, prices
from .model import DB, MART

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.abspath(__file__))))))
OUT_DIR = os.path.join(REPO, "docs", "indicators")
SOURCE_LINK = "../../platform/src/retail_platform/indicators/{}.py"


def source_sha256(module) -> str:
    with open(module.__file__, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def _header(module, name: str, title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        "**Generated by `make indicators-contract`.** Do not hand-edit: this page is derived",
        f"from [`{name}.py`]({SOURCE_LINK.format(name)}), where the query and the explanation",
        "live together.",
        "",
        f"Derived from `{name}.py` sha256 `{source_sha256(module)}` — a hash, not a date, so",
        "regenerating an up-to-date page changes no byte.",
        "",
    ]


def _boundary(extra_target: str = "") -> list[str]:
    return [
        "## Boundary and credentials",
        "",
        "| | |",
        "|---|---|",
        f"| Target | schema `{MART}` in database `{DB}` — and **only** MART{extra_target} |",
        "| Role | `retail_reader`, the BI role. Reads MART; denied on GOLD and STAGE |",
        "| Session | opens with `set role retail_reader` (`streamlit/connection.py`) |",
        "| Authentication | local dev user/password, defaulted in `postgres_load.py` and "
        "overridable via `.env`. No secret in the repo |",
        "| Writes | none |",
        "",
    ]


def _parameters(with_term: bool) -> list[str]:
    lines = [
        "## Parameters",
        "",
        "Bound, never concatenated — nothing can be injected through a selector or a prompt.",
        "",
        "| Parameter | Type | Use |",
        "|---|---|---|",
        "| `%(start)s` | ISO date | lower bound, inclusive |",
        "| `%(end)s` | ISO date | upper bound, inclusive |",
        "| `%(warehouses)s` | comma-separated list | `wh = any(string_to_array(%(warehouses)s, ','))` |",
    ]
    if with_term:
        lines.append("| `%(term)s` | `%...%` wildcard | `display_name ilike %(term)s` — the wildcard "
                     "lives in the bound VALUE |")
    return lines + ["", "Indicators marked **no date axis** ignore `start`/`end`.", ""]


def _catalog(indicators) -> list[str]:
    groups: dict[str, list] = {}
    for indicator in indicators:
        groups.setdefault(indicator.group, []).append(indicator)
    lines = ["## Index", ""]
    for group in sorted(groups):
        lines.append(f"- **{group}**")
        lines += [f"  - [{i.title}](#{i.key})" for i in groups[group]]
    lines.append("")
    for group in sorted(groups):
        lines += [f"## {group}", ""]
        for i in groups[group]:
            lines += [
                f'<a id="{i.key}"></a>',
                f"### {i.title}",
                "",
                "| | |",
                "|---|---|",
                f"| Key | `{i.key}` |",
                f"| Question | {i.question} |",
                f"| Source grain | `{i.grain}` |",
                f"| Data kind | {i.kind} |",
                f"| Marts | {', '.join(f'`{m}`' for m in i.marts)} |",
                f"| Date axis | {'yes' if i.dated else '**no** — current version'} |",
                "",
            ]
            if i.caveats:
                lines += ["**Caveats when rebuilding elsewhere**", ""]
                lines += [f"{n}. {text}" for n, text in enumerate(i.caveats, 1)]
                lines.append("")
            lines += ["```sql", i.sql.strip(), "```", ""]
    return lines


def _auxiliary(module, what_changed: str) -> list[str]:
    lines = ["---", "", "## Auxiliary queries", "",
             f"Not business indicators. `FRESHNESS` is what makes a new load **visible**: "
             f"without it, the numbers change and nobody knows {what_changed}.", ""]
    for sql in (module.FRESHNESS, module.WINDOW, module.WAREHOUSES):
        lines += ["```sql", sql.strip(), "```", ""]
    return lines


def render_operations() -> str:
    lines = _header(operations, "operations", "Operations indicators")
    lines += [
        "## What it's for",
        "",
        "Reviewing each indicator before rebuilding it in a BI tool or exposing it to a",
        "language model: the question, the grain, observed vs synthetic, the exact SQL, and",
        "the caveats — the cases where the obvious measure is plausible and wrong.",
        "",
    ]
    lines += _boundary() + _parameters(with_term=False) + _catalog(operations.INDICATORS)
    lines += [
        '<a id="out-of-scope"></a>',
        "## What the catalog does NOT answer",
        "",
        "A declared absence is worth more than an invented indicator. Each item carries the",
        "**trigger** that would unlock it.",
        "",
    ]
    for title, reason, trigger in operations.OUT_OF_SCOPE:
        lines += [f"### {title}", "", reason, "", f"**Trigger:** {trigger}", ""]
    lines += _auxiliary(operations, "the base changed")
    return "\n".join(lines) + "\n"


def render_prices() -> str:
    lines = _header(prices, "prices", "Price-watch indicators")
    lines += [
        "## What it's for",
        "",
        "Mercadona catalog price movement — drops, rises, category volatility, per-product",
        "history — separate from the operations catalog, which covers orders, fulfillment,",
        "stock and demand.",
        "",
        '## What "offer" means here',
        "",
        "There is no promotional flag anywhere in the warehouse: the source's own",
        "`price_decreased` flag is false on 100% of rows even when prices moved. Every drop",
        "below is a `change_type = 'preco_alterado'` row with a negative delta — a REAL,",
        "OBSERVED price decrease, never a confirmed marketing campaign.",
        "",
    ]
    lines += _boundary(" (`mart_price_evolution`, `mart_assortment_daily`)")
    lines += _parameters(with_term=True) + _catalog(prices.INDICATORS)
    lines += _auxiliary(prices, "the catalog was re-cut")
    return "\n".join(lines) + "\n"


PAGES = {"operations.md": render_operations, "prices.md": render_prices}


def main(out_dir: str = OUT_DIR) -> int:
    os.makedirs(out_dir, exist_ok=True)
    for name, render in PAGES.items():
        path = os.path.join(out_dir, name)
        with open(path + ".tmp", "w", encoding="utf-8") as handle:
            handle.write(render())
        os.replace(path + ".tmp", path)
        print(f"written .......... {os.path.relpath(path, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
