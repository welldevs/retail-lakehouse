# --------------------------------------------------------------------------------------
# The fold, pure: event + previous state -> new state
# --------------------------------------------------------------------------------------
#
# THIRD INDEPENDENT IMPLEMENTATION OF THE SAME FOLD. The first is `silver_order.sql` (window
# functions over the whole log); the second is `orders_oltp.plan()` (incremental, in SQL,
# inside a transaction); this one is incremental, in memory, fed by the broker.
#
# Three independent paths to the same number is what makes `orders-reconcile` mean
# something. Milestone 4 already showed the payoff: two folds disagreeing found two defects
# no test caught, because each was internally coherent.

APPLY = "apply"
DUPLICATE = "duplicate"
GAP = "gap"

TERMINAL_STATES = (
    "PAYMENT_FAILED", "CANCELLED", "DELIVERY_FAILED", "RETURNED", "DELIVERED",
)

STATE_AFTER = {
    "order_placed": "PLACED",
    "order_payment_authorized": "CONFIRMED",
    "order_payment_failed": "PAYMENT_FAILED",
    "order_cancelled": "CANCELLED",
    "order_picking_started": "PICKING",
    "order_line_substituted": "PICKING",
    "order_line_removed": "PICKING",
    "order_picked": "PICKED",
    "order_dispatched": "IN_TRANSIT",
    "order_delivered": "DELIVERED",
    "order_delivery_failed": "DELIVERY_FAILED",
    "order_returned": "RETURNED",
}


def decide(last_sequence_no, event) -> str:
    """Apply, discard as a duplicate, or reject as a gap. Pure function.

    DEDUPLICATION DOES NOT USE A SET OF `event_id`s. A set grows without bound and forces
    inventing an expiry policy — and every expiry policy is a window in which the duplicate
    gets through again. Comparing `sequence_no` with the existing state is BOUNDED by
    construction (one integer per order) and has no window.

    That only works because per-key order is guaranteed by the broker. If it were not, a
    duplicate could arrive BEFORE the original and would be classified as a gap. That is why
    `key = order_id` is not a configuration detail: it is this function's premise.
    """
    sequence_no = event["sequence_no"]
    if last_sequence_no is None:
        last_sequence_no = 0
    if sequence_no <= last_sequence_no:
        return DUPLICATE
    if sequence_no > last_sequence_no + 1:
        return GAP
    return APPLY


def _ts(value: str) -> datetime:
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def fold_event(state, event, *, sla_minutes: int):
    """The order's new state after this event. Does not mutate `state`.

    Reads no database, has no clock, draws no random numbers: two consumers with the same
    sequence of events reach the same state. That is what lets replay be a verification and
    not a hope.
    """
    kind = event["event_type"]
    if kind not in STATE_AFTER:
        raise OrdersStreamError(
            f"{event['order_id']} seq={event['sequence_no']}: event_type {kind!r} outside the "
            f"vocabulary this projection knows"
        )
    payload = event["payload"]
    occurred_at = _ts(event["occurred_at"])

    if kind == "order_placed":
        if state is not None:
            raise OrdersStreamError(f"{event['order_id']}: order_placed on an existing order")
        state = {
            "order_id": event["order_id"],
            "wh": event["wh"],
            "order_date": occurred_at.date(),
            "customer_id": payload["customer_id"],
            "placed_at": occurred_at,
            "line_count": payload["line_count"],
            "gross_amount": payload["gross_amount"],
            "net_amount": None,
            "picked_line_count": None,
            "returned_amount": None,
            "delivered_within_slot": None,
            "substituted_lines": 0,
            "removed_lines": 0,
            "confirmed_at": None,
            "picking_started_at": None,
            "picked_at": None,
            "dispatched_at": None,
            "terminal_at": None,
            "picking_minutes": None,
            "sla_breached": None,
            "events_applied": 0,
        }
    else:
        if state is None:
            raise OrdersStreamError(
                f"{event['order_id']} seq={event['sequence_no']} {kind}: event for an order "
                f"the projection never saw — order_placed did not arrive"
            )
        state = dict(state)

    state["status"] = STATE_AFTER[kind]
    state["last_sequence_no"] = event["sequence_no"]
    state["updated_at"] = occurred_at
    state["events_applied"] = state["events_applied"] + 1

    if kind == "order_payment_authorized":
        state["confirmed_at"] = occurred_at
    elif kind == "order_picking_started":
        state["picking_started_at"] = occurred_at
    elif kind == "order_line_substituted":
        state["substituted_lines"] += 1
    elif kind == "order_line_removed":
        state["removed_lines"] += 1
    elif kind == "order_picked":
        state["picked_at"] = occurred_at
        state["net_amount"] = payload["picked_amount"]
        state["picked_line_count"] = payload["picked_line_count"]
        # THE ONLY CALCULATION THIS PROJECTION DOES THAT THE BATCH WOULD NOT DO SOONER. Here
        # it is available the instant the event arrives; in batch, only after the day's
        # partition closes. It is the latency difference that justifies a consumer — the
        # mechanism exists and is measurable. Whether ANYONE NEEDS that latency is another
        # question, and it remains unanswered in this repository: see ARCHITECTURE.md.
        if state["picking_started_at"] is not None:
            minutes = (occurred_at - state["picking_started_at"]).total_seconds() / 60.0
            state["picking_minutes"] = round(minutes, 2)
            state["sla_breached"] = minutes > sla_minutes
    elif kind == "order_dispatched":
        state["dispatched_at"] = occurred_at
    elif kind == "order_delivered":
        state["delivered_within_slot"] = payload["delivered_within_slot"]
    elif kind == "order_returned":
        state["returned_amount"] = payload["returned_amount"]
    elif kind in ("order_cancelled", "order_payment_failed"):
        # Died before picking: `net_amount` stays undetermined, exactly as in the OLTP and
        # in Silver. Filling it with the placed amount would make the column answer another
        # question under the same name — the defect Milestone 4 found.
        pass

    if state["status"] in TERMINAL_STATES:
        state["terminal_at"] = occurred_at
    return state


def read_sla_minutes(seeds_dir: str = DEFAULT_SEEDS_DIR) -> int:
    """The threshold comes from the premises seed, not from a constant in this module.

    Same discipline as the `currency` var: the premise travels with the number. A constant
    here could diverge from what the generator used, and the alert would start measuring
    something else.
    """
    path = os.path.join(seeds_dir, PREMISES_SEED)
    try:
        with open(path, encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                if row["premise_key"] == "sla_minutes_picking":
                    return int(float(row["value"]))
    except OSError as exc:
        raise OrdersStreamError(f"could not read {path}: {exc}") from exc
    raise OrdersStreamError(f"{path} does not declare sla_minutes_picking")


