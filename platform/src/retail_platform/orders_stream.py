@dataclass
class ProjectResult:
    """The result of consuming the topic.

    `orders` AND `sla_breaches` ARE DISTINCT COUNTS, AND THAT COST A DEFECT. Up to Phase 7
    they were integers summed batch by batch, and an order whose events fall in different
    batches was counted once PER BATCH. Measured on 2026-09-01, consuming 1,433,723 events:
    the consumer printed "SLA breached 31,908" while the projection and Silver agreed on
    19,136.

    Nothing broke, and that is the point — the number was plausible, had the right order of
    magnitude, and the label said something other than what it measured ("writes of breached
    orders", not "breached orders"). It is the same class as `orders_touching_category`,
    which does not sum across categories, and the only one no count test catches.

    `applied`, `duplicates` and `batches` remain sums: they are EVENT counts, and an event
    does not repeat across batches — what repeats is the order.
    """

    applied: int = 0
    duplicates: int = 0
    batches: int = 0
    gaps: list = field(default_factory=list)
    order_ids: set = field(default_factory=set)
    sla_breached_ids: set = field(default_factory=set)

    @property
    def orders(self) -> int:
        """DISTINCT orders touched."""
        return len(self.order_ids)

    @property
    def sla_breaches(self) -> int:
        """DISTINCT orders with the picking SLA breached.

        Must match `count_if(sla_breached)` in the projection and in `silver_order` — they
        are three independent folds, and their agreement is the verification.
        """
        return len(self.sla_breached_ids)


def project_batch(projection, events, *, sla_minutes: int) -> ProjectResult:
    """Applies a batch to the read model. Pure with respect to the broker: knows no offsets.

    Separate from `project()` on purpose — this is where the deduplication semantics live,
    and they must be exercisable without any broker.
    """
    result = ProjectResult()
    states = projection.load({event["order_id"] for event in events})
    touched: dict = {}

    for event in events:
        order_id = event["order_id"]
        current = touched.get(order_id, states.get(order_id))
        verdict = decide(None if current is None else current["last_sequence_no"], event)
        if verdict == DUPLICATE:
            result.duplicates += 1
            continue
        if verdict == GAP:
            result.gaps.append(
                f"{order_id}: got seq={event['sequence_no']} with "
                f"last_sequence_no={None if current is None else current['last_sequence_no']}"
            )
            continue
        touched[order_id] = fold_event(current, event, sla_minutes=sla_minutes)
        result.applied += 1

    projection.save(list(touched.values()))
    result.order_ids.update(touched)
    result.sla_breached_ids.update(
        order_id for order_id, state in touched.items() if state.get("sla_breached"))
    return result


def project(consumer, projection, *, sla_minutes: int, batch_size: int = 500,
            idle_timeout: float = 5.0, max_messages: int | None = None,
            strict: bool = True) -> ProjectResult:
    """Consumes until the topic runs dry (or up to `max_messages`), projecting in batches.

    THE OFFSET IS COMMITTED AFTER THE WRITE. If the process dies between the write and the
    commit, the batch is redelivered and deduplication discards it — at-least-once delivery,
    exactly-once effect on the projection. Committing first would trade that for
    at-most-once without anyone choosing, which is what `enable.auto.commit` does by default.
    """
    total = ProjectResult()
    pending: list = []
    idle_since = None

    while True:
        message = consumer.poll(1.0)
        if message is None:
            if pending:
                _flush(projection, consumer, pending, sla_minutes, total, strict)
                pending = []
                idle_since = None
                continue
            idle_since = idle_since or time.monotonic()
            if time.monotonic() - idle_since >= idle_timeout:
                break
            continue
        if message.error():
            raise OrdersStreamError(f"broker error: {message.error()}")

        idle_since = None
        try:
            pending.append(json.loads(message.value().decode("utf-8")))
        except ValueError as exc:
            raise OrdersStreamError(
                f"unreadable message at {message.topic()}[{message.partition()}]"
                f"@{message.offset()}: {exc}"
            ) from exc

        if len(pending) >= batch_size:
            _flush(projection, consumer, pending, sla_minutes, total, strict)
            pending = []
        if max_messages is not None and total.applied + total.duplicates >= max_messages:
            break

    if pending:
        _flush(projection, consumer, pending, sla_minutes, total, strict)
    return total


def _flush(projection, consumer, events, sla_minutes, total, strict) -> None:
    try:
        batch = project_batch(projection, events, sla_minutes=sla_minutes)
    except Exception:
        projection.rollback()
        raise
    projection.commit()
    # ONLY AFTER THE WRITE IS DURABLE. This order is the difference between at-least-once
    # and at-most-once, and it does not show up in any test that only counts messages.
    consumer.commit(asynchronous=False)

    total.applied += batch.applied
    total.duplicates += batch.duplicates
    # UNION, not sum: see the ProjectResult docstring. Summing counted the same order once
    # per batch it appeared in.
    total.order_ids |= batch.order_ids
    total.sla_breached_ids |= batch.sla_breached_ids
    total.gaps.extend(batch.gaps)
    total.batches += 1
    if batch.gaps and strict:
        raise OrdersStreamError(
            "GAP in an order's sequence: the transport lost an event. "
            + "; ".join(batch.gaps[:3])
        )


def build_consumer(bootstrap: str = DEFAULT_BOOTSTRAP, group: str = DEFAULT_GROUP,
                   *, topic: str = DEFAULT_TOPIC, from_beginning: bool = False):
    try:
        from confluent_kafka import Consumer
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError(
            "confluent-kafka is not installed in this venv. Run `make venv`."
        ) from exc
    consumer = Consumer({
        "bootstrap.servers": bootstrap,
        "group.id": group,
        # NEVER true. See the module header: automatic commit moves on the timer, not on
        # the write, and delivers at-most-once without anyone having chosen it.
        "enable.auto.commit": False,
        "auto.offset.reset": "earliest" if from_beginning else "latest",
        "session.timeout.ms": 45000,
        "client.id": "orders-project",
    })
    consumer.subscribe([topic])
    return consumer


