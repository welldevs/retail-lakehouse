@dataclass
class PublishResult:
    published: int = 0
    failed: int = 0
    batches: int = 0
    errors: list = field(default_factory=list)


def publish_batch(connection, producer, topic: str, batch_size: int) -> int:
    """Drains ONE batch from the outbox. Returns how many rows were published and marked.

    `for update skip locked` is what allows more than one publisher without coordination:
    each takes a different batch and none waits for the other. `order by outbox_id` keeps
    insertion order within the batch, which per key is the order of the events.

    THE DUPLICATION WINDOW IS HERE, and it is explicit: between `flush()` (the broker has
    accepted) and `commit()` (`published_at` is durable) the process may die. If it dies,
    the batch goes back to the queue and is republished. There is no transaction between
    Postgres and Kafka that closes this — the alternative would be marking first and LOSING,
    which is worse. See the module header.
    """
    acked: dict = {}
    failures: list = []

    def callback_for(outbox_id):
        """One callback per message, closing over the `outbox_id`.

        confluent-kafka's `produce()` carries no opaque user payload, and correlating the
        ack by message content would be fragile. The closure is what guarantees the marked
        row is the row the broker accepted.
        """
        def on_delivery(err, _message):
            if err is not None:
                failures.append((outbox_id, str(err)))
            else:
                acked[outbox_id] = True
        return on_delivery

    with connection.cursor() as cur:
        cur.execute(
            """
            select outbox_id, order_id, event_json
              from outbox
             where published_at is null
             order by outbox_id
             for update skip locked
             limit %s
            """,
            (batch_size,),
        )
        rows = cur.fetchall()
        if not rows:
            connection.rollback()
            return 0

        for outbox_id, order_id, event_json in rows:
            producer.produce(
                topic,
                key=order_id.encode("utf-8"),
                value=event_json.encode("utf-8"),
                on_delivery=callback_for(outbox_id),
            )
        producer.flush()

        if failures:
            # Nothing is marked: the whole batch goes back to the queue. Marking only the
            # ones that passed would leave a gap in the middle of a key, and a gap is the
            # only defect the consumer CANNOT absorb.
            connection.rollback()
            raise OrdersStreamError(
                f"{len(failures)} of {len(rows)} messages rejected by the broker; "
                f"none marked as published. First: {failures[0][1]}"
            )

        cur.execute(
            "update outbox set published_at = now() where outbox_id = any(%s)",
            (list(acked),),
        )
        marked = cur.rowcount
    connection.commit()
    return marked


def publish(connection, producer, topic: str, *, batch_size: int = 1000,
            max_batches: int | None = None) -> PublishResult:
    result = PublishResult()
    while max_batches is None or result.batches < max_batches:
        published = publish_batch(connection, producer, topic, batch_size)
        if published == 0:
            break
        result.batches += 1
        result.published += published
    return result


def build_producer(bootstrap: str = DEFAULT_BOOTSTRAP):
    """Idempotent producer. Imports confluent_kafka on demand.

    `enable.idempotence` eliminates duplicates from RETRY WITHIN THE SESSION and preserves
    per-partition order even with several requests in flight. It does NOT cover the process
    dying before the outbox commit — that duplicate belongs to the design, not the
    transport, and the consumer is what absorbs it.

    `acks=all` is a consequence of `enable.idempotence` and is not written here on purpose:
    duplicating implicit configuration is how it starts diverging from the library.
    """
    try:
        from confluent_kafka import Producer
    except ImportError as exc:  # pragma: no cover - depends on the environment
        raise OrdersStreamError(
            "confluent-kafka is not installed in this venv. Run `make venv`."
        ) from exc
    return Producer({
        "bootstrap.servers": bootstrap,
        "enable.idempotence": True,
        "compression.type": "zstd",
        "linger.ms": 20,
        "client.id": "orders-publish",
    })


