def ensure_database(dsn: str) -> bool:
    """Creates the projection database if it does not exist. Returns True if it created it.

    `create database` does not run inside a transaction, so this is the only connection in
    the platform that opens in autocommit — and it writes nothing else.
    """
    try:
        import psycopg
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("psycopg is not installed in this venv.") from exc
    from urllib.parse import urlparse

    parsed = urlparse(dsn)
    name = parsed.path.lstrip("/")
    if not name:
        raise OrdersStreamError(f"DSN without a database name: {dsn}")
    admin = dsn.replace(f"/{name}", "/postgres", 1)
    with psycopg.connect(admin, autocommit=True) as connection:
        with connection.cursor() as cur:
            cur.execute("select 1 from pg_database where datname = %s", (name,))
            if cur.fetchone():
                return False
            cur.execute(f'create database "{name}"')
    return True


def projection_connect(dsn: str = None):
    try:
        import psycopg
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("psycopg is not installed in this venv.") from exc
    try:
        return psycopg.connect(dsn or DEFAULT_PROJECTION_DSN)
    except psycopg.Error as exc:
        raise OrdersStreamError(
            f"could not connect to the projection ({dsn or DEFAULT_PROJECTION_DSN}): {exc}\n"
            "Run `make stream-up`."
        ) from exc


def create_projection_schema(connection) -> None:
    with connection.cursor() as cur:
        cur.execute(PROJECTION_DDL)
    connection.commit()
