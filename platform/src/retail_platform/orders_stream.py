"""Transport, replay and idempotent consumption of the order events.

WHAT THIS MILESTONE PROVES, AND WHAT IT REFUSES TO CLAIM.

Installing a broker and publishing messages proves nothing — ARCHITECTURE.md itself already
rejected that version in writing. What must be proven, and what this module exists to make
demonstrable, are four distinct things:

  1. FAITHFUL TRANSPORT. Every outbox event reaches the topic, unaltered. Proven by
     re-reading the topic from offset 0 and reproducing the `sha256` of the 16 manifests.

  2. DELIVERY SEMANTICS, STATED PRECISELY. This pipeline is AT-LEAST-ONCE from producer to
     broker, not exactly-once. The reason is structural and has no cheap fix: marking
     `published_at` in Postgres and receiving the Kafka ack are two writes in two systems,
     and there is no transaction between them. The choice is which side to err on:

         publish -> ack -> mark     dying in the middle REPUBLISHES   (at-least-once)
         mark    -> publish         dying in the middle LOSES         (at-most-once)

     Losing an event is irreversible; duplicating is absorbable downstream. That is why the
     order is the first one, and why the consumer must be idempotent — not for elegance,
     by obligation.

     `enable.idempotence=true` on the producer does NOT solve this, and conflating the two
     is the most common mistake here: it eliminates duplicates generated by RETRY WITHIN
     THE producer's SESSION. A duplicate generated by the process dying before the outbox
     commit is out of its reach.

  3. IDEMPOTENT CONSUMPTION. The consumer deduplicates by `(order_id, sequence_no)` against
     the state it already has — not by a set of `event_id`s that grows without bound. That
     is possible BECAUSE per-key order is guaranteed: a duplicate always arrives after the
     original, with `sequence_no <= last_sequence_no`. That is what makes `key = order_id`
     a load-bearing piece, not decoration.

     The same comparison catches the opposite case: `sequence_no > last + 1` is a GAP, and a
     gap is LOSS. The consumer refuses loudly instead of applying a state that skipped a step.

  4. REPLAY. Rewinding the group to the start and reprocessing the whole topic leaves the
     projection identical — same digest. It is the same additivity property as the Source,
     one level further and in a medium that is not disk.

THE OFFSET IS COMMITTED AFTER THE WRITE, never before, and `enable.auto.commit` is false.
Automatic commit would deliver at-most-once without anyone choosing it: the offset advances
on a timer, and an event between the advance and the write simply did not happen.

THE PROJECTION LIVES IN ANOTHER DATABASE. `live_order_state` is a downstream READ MODEL,
and cannot share a transaction with the OLTP that is the source of truth — if it could, the
temptation to write both together would erase the distinction between the system that
decides and the one that observes.
"""

