def read_topic(bootstrap: str, topic: str, *, idle_timeout: float = 6.0) -> list:
    """Reads the whole topic from offset 0, with no persistent group. For checking only.

    Uses a clock-derived `group.id` and commits NOTHING: a check that touched the production
    consumer's offset would change what it came to measure.
    """
    try:
        from confluent_kafka import Consumer, TopicPartition
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("confluent-kafka is not installed in this venv.") from exc

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f")
    consumer = Consumer({
        "bootstrap.servers": bootstrap,
        "group.id": f"inspect-{stamp}",
        "enable.auto.commit": False,
        "auto.offset.reset": "earliest",
    })
    try:
        meta = consumer.list_topics(topic, timeout=15)
        if topic not in meta.topics or meta.topics[topic].error is not None:
            raise OrdersStreamError(f"topic {topic!r} does not exist on broker {bootstrap}")
        partitions = sorted(meta.topics[topic].partitions)
        consumer.assign([TopicPartition(topic, p, 0) for p in partitions])

        messages = []
        idle_since = None
        while True:
            message = consumer.poll(1.0)
            if message is None:
                idle_since = idle_since or time.monotonic()
                if time.monotonic() - idle_since >= idle_timeout:
                    break
                continue
            if message.error():
                raise OrdersStreamError(f"broker error: {message.error()}")
            idle_since = None
            messages.append({
                "partition": message.partition(),
                "offset": message.offset(),
                "key": message.key().decode("utf-8") if message.key() else None,
                "value": message.value().decode("utf-8"),
            })
        return messages
    finally:
        consumer.close()


def topic_watermarks(bootstrap: str, topic: str) -> dict:
    try:
        from confluent_kafka import Consumer, TopicPartition
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("confluent-kafka is not installed in this venv.") from exc
    consumer = Consumer({"bootstrap.servers": bootstrap, "group.id": "watermarks"})
    try:
        meta = consumer.list_topics(topic, timeout=15)
        if topic not in meta.topics or meta.topics[topic].error is not None:
            raise OrdersStreamError(f"topic {topic!r} does not exist on broker {bootstrap}")
        out = {}
        for partition in sorted(meta.topics[topic].partitions):
            low, high = consumer.get_watermark_offsets(
                TopicPartition(topic, partition), timeout=10
            )
            out[partition] = {"low": low, "high": high}
        return out
    finally:
        consumer.close()


def group_lag(bootstrap: str, topic: str, group: str) -> dict:
    """Lag per partition: `high watermark - committed offset`.

    Reads the committed offset with a consumer of the SAME group but without `subscribe`, so
    as not to trigger a rebalance on any production consumer that is running.
    """
    try:
        from confluent_kafka import Consumer, TopicPartition, OFFSET_INVALID
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("confluent-kafka is not installed in this venv.") from exc
    marks = topic_watermarks(bootstrap, topic)
    consumer = Consumer({"bootstrap.servers": bootstrap, "group.id": group,
                         "enable.auto.commit": False})
    try:
        wanted = [TopicPartition(topic, p) for p in sorted(marks)]
        committed = consumer.committed(wanted, timeout=15)
        out = {}
        for entry in committed:
            high = marks[entry.partition]["high"]
            offset = None if entry.offset in (OFFSET_INVALID, -1001) else entry.offset
            out[entry.partition] = {
                "committed": offset,
                "high": high,
                "lag": high - (offset if offset is not None else marks[entry.partition]["low"]),
            }
        return out
    finally:
        consumer.close()


def reset_group(bootstrap: str, topic: str, group: str) -> int:
    """Rewinds the group to the start of the topic. It is the replay verb.

    Does not wipe the projection: the point of replay is precisely to reprocess everything ON
    TOP of the existing state and the result not change. Wiping first would prove something
    else (that the fold is deterministic), not this (that consumption is idempotent).
    """
    try:
        from confluent_kafka import Consumer, TopicPartition
    except ImportError as exc:  # pragma: no cover
        raise OrdersStreamError("confluent-kafka is not installed in this venv.") from exc
    marks = topic_watermarks(bootstrap, topic)
    consumer = Consumer({"bootstrap.servers": bootstrap, "group.id": group,
                         "enable.auto.commit": False})
    try:
        offsets = [TopicPartition(topic, p, marks[p]["low"]) for p in sorted(marks)]
        consumer.commit(offsets=offsets, asynchronous=False)
        return len(offsets)
    finally:
        consumer.close()


