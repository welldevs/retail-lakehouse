-- THE STOCK BALANCE, read from the Iceberg table that SPARK writes.
--
-- GRAIN: (wh, source_product_id, stock_date). One row per series per day of the window,
-- including days with no sales — without them the balance would "skip" precisely the days
-- a replenishment arrives, and coverage in days would stop meaning anything.
--
-- WHY IT COMES IN THROUGH ICEBERG AND NOT THROUGH RAW. This is the only Silver model that
-- does not derive from a Source: stock is not observed anywhere in this project. Mercadona
-- does not publish balances, INE does not measure retail and MAPA measures household
-- consumption. The ledger is COMPUTED, from the consumption observed in orders plus a
-- policy declared in `stock_premises_seed` — and what computes it is a Spark job, because
-- the shape of the computation is not SQL.
--
-- THE SHAPE, in one sentence: it is a running sum whose INPUTS are generated by decisions
-- taken from the state itself. The balance falls below the reorder point, an order is
-- issued, it arrives two days later and changes the balance of the following days, which
-- decides whether there is a new order. A window function reads the whole partition but
-- does not write back to it. This was MEASURED: `make check-spark-iceberg`, question S7b,
-- runs the same input through both shapes and the SQL running sum diverges on 14 of the
-- case's 30 days, reaching a balance of -70.
--
-- THE METADATA PATH COMES FROM A VAR, for the same reason as `silver_live_order_state`:
-- DuckDB REFUSES to discover on its own which is the current metadata of an Iceberg table,
-- and the refusal is right — scanning storage may find a commit that did not happen. The
-- one who knows is the catalog, and `make silver` asks it.
--
-- AND THIS MODEL STAYS OUT OF THE BUILD WHILE THE TABLE DOES NOT EXIST. It is not fault
-- tolerance: it is the property that keeps Spark OPTIONAL. A fresh clone of the
-- repository, where nobody pulled the Spark image, builds the whole Silver — the
-- `silver_gate.py` gate removes from here what depends on a missing table, and
-- `test_O_SPARK_E_OPCIONAL_e_isto_e_o_que_prova` guards that.
--
-- `written_by` is PROVENANCE. In this table it is always 'spark', and it is still worth
-- it: it is how a query finds out there is a third writer in the catalog, and the first
-- outside Python — which is the property that justified Iceberg and was only claimed.
