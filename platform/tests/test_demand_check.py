"""The cohort section of the reality check.

Why this section deserves its own test: the effect of the cohort layer is ENTIRELY
conditional — the aggregate does not move, on purpose. A report that published only totals
would conclude the phase did nothing, and that conclusion would be indistinguishable from
the truth if the phase really had done nothing. It is the same reason Phase 4 refused to
judge realism by revenue.
"""

from __future__ import annotations

import unittest

from retail_platform import demand_check as dc


def _groups(**weights) -> dict:
    return {
        name: {
            "linhas": qty,
            "unidades": str(qty),
            "receita": str(qty * 2),
            "kg_l": str(qty),
            "linhas_sem_kg": 0,
        }
        for name, qty in weights.items()
    }


def _snapshot(with_cohort: bool = True) -> dict:
    base = {
        "measured_at_utc": "2026-09-01T00:00:00Z",
        "groups": _groups(VINO=100, ARROZ=100, NO_FOOD=100),
    }
    if not with_cohort:
        return {**base, "cohorts": None, "warehouses": None}
    return {
        **base,
        "cohorts": {
            "LT35": {
                g: {"linhas": n, "unidades": str(n), "receita": str(n)}
                for g, n in (("VINO", 10), ("ARROZ", 60), ("NO_FOOD", 30))
            },
            "GE65": {
                g: {"linhas": n, "unidades": str(n), "receita": str(n)}
                for g, n in (("VINO", 50), ("ARROZ", 20), ("NO_FOOD", 30))
            },
        },
        "warehouses": {
            "bcn1": {"pedidos": 1436, "clientes": 1251},
            "mad1": {"pedidos": 1176, "clientes": 1049},
        },
    }


class CohortSectionTest(unittest.TestCase):
    def test_the_page_carries_the_cohort_dimension(self):
        # The error this catches is the same one §7 of the previous phase existed to prevent,
        # one axis further: a report that publishes only the dimension in which nothing changed.
        page = "\n".join(dc._cohort_section(_snapshot(), None))
        self.assertIn("Propensity by buyer cohort", page)
        self.assertIn("LT35", page)
        self.assertIn("GE65", page)
        self.assertIn("Frequency by autonomous community", page)

    def test_the_band_ratio_is_computed_and_sorts_the_table(self):
        # The column that sums up the whole phase in one line. With 10% against 50% wine, the
        # ratio is 5.00 — and wine must appear BEFORE rice, whose ratio is 0.33.
        page = "\n".join(dc._cohort_section(_snapshot(), None))
        self.assertIn("| VINO | 10.00 | 50.00 | 5.00 |", page)
        self.assertLess(page.index("| VINO |"), page.index("| ARROZ |"))

    def test_missing_cohort_is_declared_not_omitted(self):
        # A window generated by an earlier model lacks the stamp. Omitting the section would
        # make the page look complete; declaring the absence says why it is not there.
        page = "\n".join(dc._cohort_section(_snapshot(with_cohort=False), None))
        self.assertIn("Not present in this window", page)
        self.assertNotIn("| VINO |", page)

    def test_orders_per_warehouse_appear_with_the_right_denominator(self):
        page = "\n".join(dc._cohort_section(_snapshot(), None))
        self.assertIn("| bcn1 | 1436 | 1251 |", page)
        self.assertIn("| mad1 | 1176 | 1049 |", page)


class TolerantMeasurementTest(unittest.TestCase):
    def test_window_without_the_band_column_can_still_be_frozen(self):
        # Without this, this phase's BEFORE could not be frozen — and without a BEFORE there is
        # no way to PROVE the aggregate did not move, which is the whole phase's acceptance
        # criterion.
        class ConnectionWithoutColumn:
            def execute(self, sql):
                raise RuntimeError("Binder Error: buyer_age_band not found")

        self.assertEqual(
            dc._measure_cohorts(ConnectionWithoutColumn()),
            {"cohorts": None, "warehouses": None},
        )


if __name__ == "__main__":
    unittest.main()
